async def seed():
    async with async_session() as db:
        # Categories
        cat_ids = {}
        for c in CATEGORIES:
            r = await db.execute(select(Category).where(Category.slug == c["slug"]))
            existing = r.scalar_one_or_none()
            if existing:
                cat_ids[c["slug"]] = existing.id
                print(f"  分类已存在: {c['name']}")
            else:
                cat = Category(name=c["name"], slug=c["slug"], icon=c["icon"],
                               sort_order=c["sort_order"], status="active")
                db.add(cat)
                await db.flush()
                cat_ids[c["slug"]] = cat.id
                print(f"  创建分类: {c['name']} (id={cat.id})")

        # Articles
        for a in ARTICLES:
            r = await db.execute(select(Article).where(Article.slug == a["slug"]))
            if r.scalar_one_or_none():
                print(f"  文章已存在: {a['title']}")
                continue
            art = Article(
                title=a["title"], slug=a["slug"], summary=a["summary"],
                content=a["content"], category_id=cat_ids[a["category"]],
                is_featured=a["is_featured"], status="published",
                published_at=datetime.now(timezone.utc),
            )
            db.add(art)
            print(f"  创建文章: {a['title']}")

        await db.commit()
        print("种子数据完成 ✅")


if __name__ == "__main__":
    asyncio.run(seed())
